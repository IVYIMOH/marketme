alter default privileges for role "postgres" in schema "public" revoke all on tables from "service_role";

create table "public"."profiles" (
  "id"           uuid                     not null,
  "display_name" character varying        not null,
  "created_at"   timestamp with time zone not null default timezone('utc'::text, now()),
  constraint "profiles_pkey" primary key (id)
);

alter table "public"."profiles"
  enable row level security;

create table "public"."todos" (
  "id"         bigint                   generated by default as identity not null,
  "created_at" timestamp with time zone not null default now(),
  constraint "todos_pkey" primary key (id)
);

alter table "public"."todos"
  enable row level security;

create type "public"."user_role" as enum (
  'buyer',
  'photographer',
  'admin'
);

alter table "public"."profiles"
  add column "role" public.user_role not null default 'buyer'::public.user_role;

create or replace function public.handle_new_user()
  returns trigger
  language plpgsql
  security definer
  AS $function$
begin
  INSERT INTO public.profiles (id, display_name, role)
  VALUES (
    new.id,
    COALESCE(new.raw_user_meta_data->>'full_name', split_part(new.email, '@', 1)), -- Uses Google name or defaults to email prefix
    'buyer' -- Default role for V2 signup
  );
  return new;
end;
$function$;

alter table "public"."profiles"
  add constraint "profiles_id_fkey" foreign key (id) references auth.users(id) on delete cascade;

create trigger on_auth_user_created
  after insert on auth.users
  for each row
  execute function public.handle_new_user();

create policy "Profiles are publicly viewable" on "public"."profiles"
  for select
  to PUBLIC
  using (true);

create policy "Public profiles are viewable by everyone" on "public"."profiles"
  for select
  to PUBLIC
  using (true);

create policy "Users can update only their own profile" on "public"."profiles"
  for update
  to PUBLIC
  using ((auth.uid() = id));

create policy "Users can update their own profile" on "public"."profiles"
  for update
  to PUBLIC
  using ((auth.uid() = id));

grant execute on function "public"."handle_new_user"() to public, "anon", "authenticated", "postgres", "service_role";

